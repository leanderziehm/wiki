import fs from 'node:fs/promises';
import path from 'node:path';

const dataPath = path.resolve('docs/.obsidian/plugins/drag-drop-sort/data.json');
const sidebarPath = path.resolve('sidebars.ts');

const data = JSON.parse(await fs.readFile(dataPath, 'utf8'));

const order = data.orders?.['/'];

if (!Array.isArray(order)) {
  throw new Error('Could not find orders["/"] in data.json');
}

const items = order.map((item) => {
  // Markdown file -> Docusaurus doc ID
  if (item.endsWith('.md')) {
    return item.slice(0, -3);
  }

  // Directory
  return {
    type: 'category',
    label: item,
    items: [
      {
        type: 'autogenerated',
        dirName: item,
      },
    ],
  };
});

const sidebars = `import type {SidebarsConfig} from '@docusaurus/plugin-content-docs';

// This file is generated. Do not edit manually.

const sidebars: SidebarsConfig = {
  tutorialSidebar: ${JSON.stringify(items, null, 2)},
};

export default sidebars;
`;

await fs.writeFile(sidebarPath, sidebars);

console.log(`Generated ${sidebarPath}`);